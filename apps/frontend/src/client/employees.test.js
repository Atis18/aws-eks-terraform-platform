import { beforeEach, describe, expect, it, vi } from "vitest";

vi.mock("../firebase/auth", () => ({
  default: {
    currentUser: {
      getIdToken: vi.fn().mockResolvedValue("test-token"),
    },
  },
}));

const response = (body, status = 200) => ({
  ok: status >= 200 && status < 300,
  status,
  json: vi.fn().mockResolvedValue(body),
});

let api;
let fetchMock;

beforeEach(async () => {
  vi.resetModules();

  fetchMock = vi.fn();
  vi.stubGlobal("fetch", fetchMock);

  api = await import("./employees");
});

describe("employee API", () => {
  it("returns an empty employee list", async () => {
    fetchMock.mockResolvedValue(response([]));

    await expect(api.getAllEmployees()).resolves.toEqual([]);

    expect(fetchMock.mock.calls[0][0]).toBe("/api/employees");
  });

  it("returns employees from REST API in backend order", async () => {
    const employees = [
      { id: "newer", name: { firstName: "Beth" }, created: 200 },
      { id: "older", name: { firstName: "Alex" }, created: 100 },
    ];

    fetchMock.mockResolvedValue(response(employees));

    const results = await api.getAllEmployees();

    expect(results).toEqual(employees);
    expect(fetchMock.mock.calls[0][0]).toBe("/api/employees");
    expect(fetchMock.mock.calls[0][1].headers.Authorization)
      .toBe("Bearer test-token");
  });

  it("creates an employee using POST with JSON body", async () => {
    const employee = {
      name: {
        firstName: "Anna",
        lastName: "Kovacs",
      },
      position: "Developer",
      level: "Junior",
      equipment: "Laptop",
    };

    const createdEmployee = {
      id: "employee-id",
      ...employee,
    };

    fetchMock.mockResolvedValue(response(createdEmployee, 201));

    await expect(api.createEmployee(employee))
      .resolves.toEqual(createdEmployee);

    const [url, options] = fetchMock.mock.calls[0];

    expect(url).toBe("/api/employees");
    expect(options.method).toBe("POST");
    expect(options.headers).toMatchObject({
      Authorization: "Bearer test-token",
      "Content-Type": "application/json",
    });

    // The PostgreSQL database generates created.
    expect(JSON.parse(options.body)).toEqual(employee);
  });

  it("updates and deletes the requested employee", async () => {
    fetchMock.mockResolvedValue(response({}));

    await api.updateEmployee("user-1", {
      level: "Senior",
      id: "should-not-be-updated",
      fullName: "generated by database",
      created: 123,
    });

    await api.deleteEmployee("user-1");

    expect(fetchMock.mock.calls[0][0])
      .toBe("/api/employees/user-1");

    expect(fetchMock.mock.calls[0][1].method).toBe("PATCH");

    expect(JSON.parse(fetchMock.mock.calls[0][1].body))
      .toEqual({ level: "Senior" });

    expect(fetchMock.mock.calls[1][0])
      .toBe("/api/employees/user-1");

    expect(fetchMock.mock.calls[1][1].method).toBe("DELETE");

    for (const [, options] of fetchMock.mock.calls) {
      expect(options.headers.Authorization)
        .toBe("Bearer test-token");
    }
  });

  it("throws a meaningful error on unsuccessful HTTP responses", async () => {
    fetchMock.mockResolvedValue(response(null, 403));

    await expect(api.getAllEmployees())
      .rejects.toThrow("Loading employees failed (HTTP 403)");

    await expect(api.deleteEmployee("user-1"))
      .rejects.toThrow("Deleting employee failed (HTTP 403)");
  });

  it("searches employees by exact first name", async () => {
    fetchMock.mockResolvedValue(response([
      {
        id: "one",
        fullName: "robert brown",
        name: { firstName: "Robert" },
      },
      {
        id: "two",
        fullName: "roberta jones",
        name: { firstName: "Roberta" },
      },
      {
        id: "three",
        fullName: "robert smith",
        name: { firstName: "Robert" },
      },
    ]));

    const employees = await api.searchEmployees("  RoBeRt ");

    expect(employees.map(({ id }) => id)).toEqual([
      "one",
      "three",
    ]);

    expect(fetchMock.mock.calls[0][0])
      .toBe("/api/employees");
  });

  it("finds an exact full-name match", async () => {
    fetchMock.mockResolvedValue(response([
      {
        id: "a",
        fullName: "robert smith",
        name: { firstName: "Robert" },
      },
      {
        id: "b",
        fullName: "robert brown",
        name: { firstName: "Robert" },
      },
    ]));

    const employees = await api.searchEmployees("Robert Smith");

    expect(employees).toHaveLength(1);
    expect(employees[0].id).toBe("a");
  });

  it("does not contact the API for an empty search", async () => {
    await expect(api.searchEmployees("  "))
      .resolves.toEqual([]);

    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("does not silently hide a failed search request", async () => {
    fetchMock.mockResolvedValue(response(null, 400));

    await expect(api.searchEmployees("Robert"))
      .rejects.toThrow("Loading employees failed (HTTP 400)");
  });
});